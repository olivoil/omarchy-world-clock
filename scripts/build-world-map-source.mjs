#!/usr/bin/env node

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const OUTPUT = fileURLToPath(new URL("../assets/world-map.svg", import.meta.url));
const CHECK = process.argv.includes("--check");
const WIDTH = 2000;
const HEIGHT = 1000;
const SOURCES = [
  {
    name: "countries with boundary lakes",
    url: "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_10m_admin_0_countries_lakes.geojson",
    sha256: "4caf607838c3cfd211a52edda259e315513390a717a11067c5eb280f766cfb78",
  },
  {
    name: "minor islands",
    url: "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_10m_minor_islands.geojson",
    sha256: "8c933ca7a4760256bdc46408355706e39764b0fa01c160c28888b90b4faec29f",
  },
];

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

async function loadSource(source) {
  const response = await fetch(source.url);
  if (!response.ok)
    throw new Error(`Could not download ${source.name}: HTTP ${response.status}`);
  const text = await response.text();
  const actualHash = sha256(text);
  if (actualHash !== source.sha256)
    throw new Error(`${source.name} checksum mismatch: ${actualHash}`);
  return JSON.parse(text);
}

function project(position) {
  const longitude = Number(position[0]);
  const latitude = Number(position[1]);
  return [
    (longitude + 180) / 360 * WIDTH,
    (90 - latitude) / 180 * HEIGHT,
  ];
}

function featurePath(geometry) {
  const polygons = geometry.type === "Polygon" ? [geometry.coordinates]
    : geometry.type === "MultiPolygon" ? geometry.coordinates : [];
  const chunks = [];
  for (const polygon of polygons) {
    for (const ring of polygon) {
      const closesItself = ring.length > 1
        && ring[0][0] === ring[ring.length - 1][0]
        && ring[0][1] === ring[ring.length - 1][1];
      const pointCount = closesItself ? ring.length - 1 : ring.length;
      if (pointCount < 3) continue;
      let path = "";
      for (let index = 0; index < pointCount; index++) {
        const [x, y] = project(ring[index]);
        path += `${index === 0 ? "M" : " "}${x.toFixed(2)},${y.toFixed(2)}`;
      }
      chunks.push(`${path}Z`);
    }
  }
  return chunks.join("");
}

function featurePaths(collection) {
  return collection.features
    .map(feature => featurePath(feature.geometry))
    .filter(Boolean)
    .map(path => `    <path d="${path}" />`)
    .join("\n");
}

const collections = await Promise.all(SOURCES.map(loadSource));
const paths = collections.map(featurePaths).join("\n");
const output = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${WIDTH} ${HEIGHT}" preserveAspectRatio="xMidYMid meet">
  <!-- Natural Earth v5.1.2, public domain. Generated by scripts/build-world-map-source.mjs. -->
  <g fill="#d9dee7" fill-opacity="0.92" fill-rule="evenodd" stroke="#c4ccd8" stroke-opacity="0.9" stroke-width="0.72" stroke-linejoin="round">
${paths}
  </g>
</svg>
`;

if (CHECK) {
  const current = readFileSync(OUTPUT, "utf8");
  if (current !== output) {
    console.error("assets/world-map.svg is out of date; run scripts/build-world-map-source.mjs.");
    process.exit(1);
  }
} else {
  writeFileSync(OUTPUT, output);
}
